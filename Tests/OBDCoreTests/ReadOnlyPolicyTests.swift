import Testing
@testable import OBDCore

@Suite struct ReadOnlyPolicyTests {
    @Test func everyServiceOutsideTheAllowlistIsDenied() {
        for sid in UInt8.min...UInt8.max where !ReadOnlyPolicy.allowedServices.contains(sid) {
            #expect(throws: OBDError.self) { try ReadOnlyPolicy.validate([sid]) }
            #expect(throws: OBDError.self) { try ReadOnlyPolicy.validate([sid, 0x01]) }
            #expect(throws: OBDError.self) { try ReadOnlyPolicy.validate([sid, 0xF1, 0x90]) }
        }
    }

    @Test func allowlistIsExactlyTheReadServices() {
        #expect(ReadOnlyPolicy.allowedServices == [0x01, 0x02, 0x03, 0x06, 0x07, 0x09, 0x0A, 0x10, 0x19, 0x22, 0x3E])
    }

    @Test(arguments: [
        [0x01, 0x00], [0x01, 0x0C], [0x01, 0x0C, 0x0D, 0x05, 0x0B, 0x10, 0x11],
        [0x02, 0x02, 0x00], [0x02, 0x0C, 0x00, 0x0D, 0x00],
        [0x03], [0x06, 0x01], [0x07], [0x09, 0x02], [0x0A],
        [0x22, 0xF1, 0x90],
        [0x19, 0x01, 0xFF], [0x19, 0x02, 0xFF], [0x19, 0x03], [0x19, 0x0A],
        [0x19, 0x04, 0xC1, 0x00, 0x87, 0xFF], [0x19, 0x06, 0xC1, 0x00, 0x87, 0xFF],
        [0x3E, 0x00], [0x3E, 0x80], [0x10, 0x01],
    ] as [[UInt8]])
    func readRequestsPass(_ payload: [UInt8]) throws {
        _ = try ReadOnlyPolicy.validate(payload)
    }

    @Test(arguments: [
        [], [0x01], [0x01, 1, 2, 3, 4, 5, 6, 7], [0x02, 0x0C], [0x03, 0x00], [0x06], [0x09],
        [0x22, 0xF1], [0x22, 0xF1, 0x90, 0xF1, 0x88],
        [0x19], [0x19, 0x02], [0x19, 0x14, 0xFF], [0x19, 0x04, 0xC1, 0x00, 0x87],
        [0x3E, 0x01], [0x10, 0x02], [0x10, 0x03], [0x10],
        [0x04], [0x14, 0xFF, 0xFF, 0xFF], [0x27, 0x01], [0x2E, 0xF1, 0x90, 0x00],
        [0x31, 0x01, 0xFF, 0x00], [0x11, 0x01], [0x28, 0x03, 0x01], [0x85, 0x02], [0x23, 0x12, 0x00, 0x00, 0x10],
    ] as [[UInt8]])
    func writesAndMalformedRequestsAreDenied(_ payload: [UInt8]) {
        #expect(throws: OBDError.self) { try ReadOnlyPolicy.validate(payload) }
    }

    @Test func kindsAreReported() throws {
        #expect(try ReadOnlyPolicy.validate([0x22, 0xF1, 0x90]) == .udsReadDataByIdentifier)
        #expect(try ReadOnlyPolicy.validate([0x19, 0x02, 0xFF]) == .udsReadDTCInformation)
        #expect(try ReadOnlyPolicy.validate([0x01, 0x0C]) == .obdCurrentData)
    }

    @Test func denialExplainsTheService() {
        do {
            _ = try ReadOnlyPolicy.validate([0x2E, 0xF1, 0x90, 0x00])
            Issue.record("2E must be denied")
        } catch let error as OBDError {
            #expect(error.code == "POLICY_DENIED")
            #expect(error.message.contains("2E"))
        } catch {
            Issue.record("unexpected error \(error)")
        }
    }
}
